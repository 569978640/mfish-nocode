SELECT DISTINCT
    a.INTERNAL_NAME,
    a.COLUMN_NAME,
    b.TABLE_NAME
FROM PBI_FEATUREPARAMETERDISPLAYCONFIG a
         JOIN (
    SELECT 'STRINGDEFINITION' AS TABLE_NAME, NAME
    FROM STRINGDEFINITION
    WHERE NAME LIKE 'com.bfces.%'
    UNION ALL
    SELECT 'BOOLEANDEFINITION' AS TABLE_NAME, NAME
    FROM BOOLEANDEFINITION
    WHERE NAME LIKE 'com.bfces.%'
    UNION ALL
    SELECT 'UNITDEFINITION' AS TABLE_NAME, NAME
    FROM UNITDEFINITION
    WHERE NAME LIKE 'com.bfces.%'
    UNION ALL
    SELECT 'TIMESTAMPDEFINITION' AS TABLE_NAME, NAME
    FROM TIMESTAMPDEFINITION
    WHERE NAME LIKE 'com.bfces.%'
) b ON a.INTERNAL_NAME = b.NAME
WHERE a.INTERNAL_NAME LIKE 'com.bfces.%';
